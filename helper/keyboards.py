"""Текстове меню та відповідні фрази для розбору намірів."""

MENU: list[list[str]] = [
    ['🆕 Нові замовлення', '📦 Стан фідів'],
    ['🖥 Статус системи', '❓ Довідка'],
]
BUTTONS: dict[str, str] = {
    '🆕 Нові замовлення': 'нові замовлення',
    '📦 Стан фідів': 'стан фідів',
    '🖥 Статус системи': 'статус системи',
    '❓ Довідка': 'що ти вмієш',
}


def to_query(text: str) -> str:
    """Замінити кнопку фразою, зберігши решту тексту без змін."""
    return BUTTONS.get(text.strip(), text)
