"""Приведення наших значень до БУКВИ довідника Єпіцентру.

Привід (27.09.2026): з 1249 значень набору 7216 записалось 63. Причина не в
якості — значення правильні за змістом, але PIM приймає лише точний збіг із
дозволеним варіантом:

    наше «Жіноча» / «жіночий»  → довідник «для жінок»      (616 значень)
    наше «Сукня»               → довідник «сукня»          (124 значення)
    наше «Боді»                → довідник «боді»           (39 значень)

Тобто сотні значень втрачались через ВЕЛИКУ ЛІТЕРУ, а вся «Стать» — через
інше формулювання. Модель тут не потрібна: це впорядкування рядків.

Порядок спроб — від найнадійнішого до найслабшого, і кожен рівень видно у
відповіді, щоб не видавати здогад за точний збіг.
"""
import re
import unicodedata

# Формулювання, де довідник каже інакше, ніж природна мова. Тільки те, що
# бачили в живих даних — вигадувати синоніми наосліп означало б вписати
# в картки значення, яких ніхто не перевіряв.
SYNONYMS = {
    'стать': {
        'жіноча': 'для жінок', 'жіночий': 'для жінок', 'жіноче': 'для жінок',
        'жінка': 'для жінок', 'для неї': 'для жінок', 'ж': 'для жінок',
        'чоловіча': 'для чоловіків', 'чоловічий': 'для чоловіків',
        'чоловіче': 'для чоловіків', 'чоловік': 'для чоловіків',
        'для нього': 'для чоловіків', 'ч': 'для чоловіків',
    },
}


def norm(text):
    """Порівняльна форма: без регістру, зайвих пробілів і різниці апострофів."""
    if not text:
        return ''
    text = unicodedata.normalize('NFKC', str(text))
    text = text.replace('’', "'").replace('`', "'").replace('ʼ', "'")
    return re.sub(r'\s+', ' ', text).strip().casefold()


def match(value, options, attr=None):
    """Значення довідника + як воно знайдене, або (None, причина).

    Рівні: `точний` → `регістр` → `синонім` → `частина`. Останній вимагає
    ОДНОЗНАЧНОСТІ: якщо наше слово міститься у двох дозволених варіантах,
    вибирати навмання не можна.
    """
    if not value or not options:
        return None, 'порожньо'
    if value in options:
        return value, 'точний'

    table = {norm(o): o for o in options}
    key = norm(value)
    if key in table:
        return table[key], 'регістр'

    syn = SYNONYMS.get(norm(attr) if attr else '', {})
    if key in syn and norm(syn[key]) in table:
        return table[norm(syn[key])], 'синонім'

    # Беремо всіх, хто ділить бодай одне слово, і приймаємо ЛИШЕ якщо він один.
    # Інакше «вечірня сукня» при варіантах «сукня» і «сукня вечірня» мовчки
    # осіла б на коротшому — тихе погіршення даних, яке ніхто б не помітив.
    words = set(key.split())
    hits = {o for k, o in table.items() if words & set(k.split())}
    if len(hits) == 1:
        return hits.pop(), 'частина'
    return None, ('неоднозначно' if hits else 'немає відповідника')


def map_values(values, options_by_attr):
    """{атрибут: значення} → ({атрибут: значення_довідника}, [звіт по кожному])."""
    out, report = {}, []
    for attr, value in (values or {}).items():
        options = options_by_attr.get(attr) or {}
        found, how = match(value, options, attr)
        report.append({'атрибут': attr, 'наше': value, 'довідник': found, 'як': how})
        if found:
            out[attr] = found
    return out, report
