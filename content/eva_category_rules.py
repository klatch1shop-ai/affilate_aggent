def resolve(section, name):
    """→ (eva_id, слаг, rule) — rule каже, чим визначено: розділом чи назвою."""
    section = (section or '').strip()
    name = name or ''
    for sec, pat, cid, slug in RULES:
        if sec and sec != section:
            continue
        if re.search(pat, name, re.I):
            return cid, slug, f'назва: /{pat}/'
    if section in SECTION:
        cid, slug = SECTION[section]
        return cid, slug, 'розділ'
    return None, None, 'НЕ ЗІСТАВЛЕНО'
