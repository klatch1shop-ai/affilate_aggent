#!/usr/bin/env python3
"""Перечистити вже зібрані ціни від аксесуарів.

Звірка назви картки з артикулом лишає й аксесуари: на Промі продають
скло, ручки й наліпки, у назві яких стоїть код моделі. Через них мінімум
ставав 10 грн при медіані 4791, і «найдешевша пропозиція» переставала
означати товар.

Перераховує `мін_конкурент` і `різниця_%` по вже збережених цінах, не
ходячи в мережу. Відкидає ціни, дешевші за 40 % медіани — поріг узятий з
розриву на реальних даних: аксесуари йшли по 10-150 грн при медіанах у
тисячах, тож проміжок між ними порожній.
"""
import json
import os
import statistics as st
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СХОВИЩЕ = os.path.join(BASE, 'data', 'katran_competitors.json')
ПОРІГ = 0.4


def main():
    сухий = '--застосувати' not in sys.argv
    d = json.load(open(СХОВИЩЕ, encoding='utf-8'))
    змінено = []
    for арт, v in d.items():
        ціни = sorted(c['ціна'] for c in (v.get('конкуренти') or []))
        if len(ціни) < 3:
            continue
        сер = st.median(ціни)
        чисті = [c for c in ціни if c >= ПОРІГ * сер]
        if not чисті or чисті[0] == v.get('мін_конкурент'):
            continue
        було = v['мін_конкурент']
        v['конкуренти'] = [c for c in v['конкуренти'] if c['ціна'] in чисті]
        v['мін_конкурент'] = чисті[0]
        v['медіана_конкурентів'] = int(st.median(чисті))
        v['скільки_пропозицій'] = len(чисті)
        v['різниця_%'] = round((v['наша'] - чисті[0]) / чисті[0] * 100, 1)
        v['відкинуто_аксесуарів'] = len(ціни) - len(чисті)
        змінено.append((арт, було, чисті[0], v['назва'][:38]))
    print(f'позицій у сховищі: {len(d)} · виправлено: {len(змінено)}')
    for арт, було, стало, назва in sorted(змінено, key=lambda x: x[1])[:12]:
        print(f'  {арт[:18]:18} мін {було:7} → {стало:7}  {назва}')
    if сухий:
        print('\nсухий прогін. Записати: --застосувати')
        return
    tmp = СХОВИЩЕ + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    os.replace(tmp, СХОВИЩЕ)
    print('\nзаписано')


if __name__ == '__main__':
    main()
