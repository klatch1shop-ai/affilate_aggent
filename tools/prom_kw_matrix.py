def _is_adj(w):
    """Чи слово схоже на означення в називному. -а/-я теж рахуємо: іменники
    на -а тут теж трапляються («пробка анальна»), але склеювання двох перших
    слів у обох випадках дає природну фразу, а от самотнє «анальна» — ні."""
    return w.endswith(('ий', 'ій', 'не', 'ні', 'ове', 'ова', 'а', 'я'))


def agree(adj_forms, noun):
    return adj_forms[GENDER_IDX[word_gender(noun)]]


def stem_set(phrase):
    """Множина основ слів. Prom зчитує «вібратор для жінок», «вібратори для
    жінок» і «вібратори жіночі» як один набір — клони не мають займати слоти."""
    return frozenset(w[:5] for w in re.findall(r'\w+', phrase.lower()) if len(w) > 2)


def head_noun(prm, category, name=''):
    '''Тип із характеристик беремо лише тоді, коли він **підтверджується
    назвою**. У фіді трапляється «Тип товару: анальний душ» у вібропробки —
    і тоді всі дев'ять фраз будуються навколо чужого слова. Назва, яку писав
    постачальник, надійніша за параметр, який хтось колись змапив.'''
    nm = (name or '').lower()
    best = None
    for k in TYPE_PARAMS:
        v = (prm.get(k) or '').strip().lower().split('|')[0].strip()
        if not v or v in NOT_A_NOUN:
            continue
        if v.split()[-1][:5] in nm:            # слово типу справді є в назві
            return v
        best = best or v
    # Назва починається з означення («Анальна вібропробка», «Потужний
    # мінівібратор»), тому одне перше слово брати не можна — це прикметник.
    # Беремо перші два змістовні слова, відкинувши маркетингові епітети.
    # Мінімум 3 літери, а не 4: інакше випадають короткі іменники — «душ»,
    # «гель», «жгут». «Анальний душ із двома насадками» давав головне слово
    # «анальний двома», бо «душ» не проходив довжину.
    words = [w for w in re.findall(r'[а-яіїєґ][а-яіїєґ\-]{2,}', nm)
             if w not in NOT_A_NOUN and w not in FLUFF and w not in NUMERALS]
    if words:
        return ' '.join(words[:2]) if len(words) > 1 and _is_adj(words[0]) else words[0]
    return best or (category or '').lower().rstrip('и') or 'іграшка'


def contradicts(phrase, purpose):
    """Ключ називає одну зону, а характеристика — іншу."""
    if not purpose:
        return False
    p = purpose.lower()
    for token, zone in ZONE.items():
        if token in phrase.lower() and zone not in p and p not in zone:
            # «вагінально-кліторні» містить обидві зони — це не суперечність
            if not any(z.split()[-1] in p for z in (zone,)):
                return True
    return False


def build(name, vendor, category, prm, description='', catname=None):
    catname = catname or category
    noun = head_noun(prm, category, name)
    ven = real_vendor(vendor)
    cyr = brand_cyr(ven, 'ua')
    purpose = (prm.get('Призначення') or '').lower()
    color = (prm.get('Колір') or '').split('|')[0].strip().lower()
    mat = (prm.get('Матеріал') or '').split('|')[0].strip().lower()
    slots = collections.OrderedDict()

    def add(layer, phrase):
        phrase = re.sub(r'\s+', ' ', phrase).strip().lower()
        lo = 1 if layer == 0 else 2      # «фалоімітатор» сам по собі — робочий запит
        if not (lo <= len(phrase.split()) <= 4):
            return
        if phrase in BROAD or not natural(phrase):
            return
        if contradicts(phrase, purpose):
            return
        if stem_set(phrase) in {stem_set(p) for p in slots}:
            return
        slots.setdefault(phrase, layer)

    # 0  базові категорійні фрази — спільні на всю категорію і це нормально
    cat_l = re.sub(r'[^а-яіїєґ\s-]', ' ', (category or '').lower()).strip()
    cat_l = re.sub(r'\s+', ' ', cat_l).replace('-', ' ')
    if cat_l:
        add(0, cat_l)
    for key, base in CATEGORY_BASE.items():
        if key in cat_l or key in noun:
            add(0, base)
            break

    # 1–2  точна категорія / конструктив
    add(1, noun)
    ph = PURPOSE_PHRASE.get(purpose)
    if ph:
        add(1, f'{noun} {ph}' if ph.startswith(('для', '3')) else f'{ph} {noun}')
    if (prm.get('Конструкція') or '').strip().lower().startswith('подвійн'):
        add(1, f'подвійний {noun}' if word_gender(noun) == 'm' else f'подвійна {noun}')

    # 3–4  бренд
    if ven:
        add(2, f'{noun} {ven.lower()}')
        if cyr:
            add(2, f'{noun} {cyr.lower()}')
        model = re.sub(re.escape(ven), '', name, flags=re.I)
        model = re.sub(r'[^\w\s-]', ' ', model)
        mw = [w for w in model.split() if re.match(r'^[A-Za-z][A-Za-z0-9-]{2,}$', w)][:2]
        if mw:
            add(2, f'{ven.lower()} {" ".join(mw).lower()}')

    # 5–6  колір, матеріал, живлення
    if color in COLOR_ADJ:
        add(3, f'{agree(COLOR_ADJ[color], noun)} {noun}')
    for key, forms in MATERIAL_ADJ.items():
        if key in mat:
            add(3, f'{agree(forms, noun)} {noun}')
            break
    power = (prm.get('Тип живлення') or '').lower()
    if 'акум' in power or 'usb' in (description or '').lower():
        add(3, f'{noun} на акумуляторі')
    elif 'батар' in power:
        add(3, f'{noun} на батарейках')

    # 7–8  особливість
    if (prm.get('Водонепроникний') or '').lower().startswith('так'):
        add(4, f'{agree(WATERPROOF_ADJ, noun)} {noun}')
    modes = prm.get('Кількість режимів вібрації') or prm.get('Кількість режимів роботи')
    if modes and str(modes).strip().isdigit():
        add(4, f'{noun} {str(modes).strip()} режимів')
    if (prm.get('Керування через застосунок (Smart)') or '').lower().startswith('так'):
        add(4, f'смарт {noun}')

    # 7–8  габарит: єдине, що відрізняє Small/Medium/Large одного артикула.
    # Без нього три варіанти однієї моделі дістають майже однаковий набір.
    dia = (prm.get('Діаметр') or '').strip().replace(',', '.')
    ln = (prm.get('Довжина') or '').strip().replace(',', '.')
    if not dia:                       # у фіді габарит часто лише в тексті назви
        mo = re.search(r'діаметр\w*\s*[-–]?\s*(\d+[.,]?\d*)\s*см', name, re.I)
        if mo:
            dia = mo.group(1).replace(',', '.')
    if not ln:
        mo = re.search(r'довжин\w*\s*[-–]?\s*(\d+[.,]?\d*)\s*см', name, re.I)
        if mo:
            ln = mo.group(1).replace(',', '.')
    vol = (prm.get('Об`єм') or prm.get("Об'єм") or prm.get('Об’єм') or '').strip()
    size = (prm.get('Розмір') or '').strip().lower()
    try:
        if dia and float(dia) >= 2:
            add(4, f'{noun} діаметр {round(float(dia))} см')
    except ValueError:
        pass
    try:
        if ln and float(ln) >= 8:
            add(4, f'{noun} {round(float(ln))} см')
    except ValueError:
        pass
    if vol and vol.replace('.', '').isdigit():
        add(4, f'{noun} {vol.split(".")[0]} мл')
    # Розмір беремо лише там, де він осмислений. У фіді трапляється «Розмір: L»
    # у парфумів — сміттєва характеристика, яка інакше потрапила б у ключі.
    if size and len(size) <= 4 and size not in NOT_A_NOUN and \
       re.search(r'білизн|костюм|чаш|боді|панчох|корсет', category, re.I):
        add(4, f'{noun} розмір {size}')

    # 7–8  ознаки з тексту — рятують «бідні» категорії без характеристик
    src = f'{name} {description[:900]}'
    for pat, tpl in FEATURE:
        if re.search(pat, src, re.I):
            add(4, tpl.format(n=noun))

    # 9  синонім / альтернатива — те, як товар називають покупці
    # Голий синонім («штучна вагіна») повторився б на сотнях карток — це той
    # самий дубль, лише під іншою назвою. Тому синонім іде з модифікатором.
    for key, syns in SYNONYM.items():
        if key in noun:
            for sy in syns:
                if ven:
                    add(5, f'{sy} {ven.lower()}')
                elif color in COLOR_ADJ:
                    add(5, f'{sy} {color}')
                else:
                    add(5, sy)
            break
    if ven and cyr:
        add(5, f'{cyr.lower()} {noun}')

    # --- резерв: добираємо до безпечного мінімуму, не далі -------------------
    if len(slots) < MIN_SAFE:
        form = (prm.get('Форма') or '').split('|')[0].strip().lower()
        if form and form not in NOT_A_NOUN:
            add(6, f'{form} {noun}' if not form.startswith(noun.split()[0]) else form)
        for key, ph in PURPOSE_PHRASE_CAT.items():
            if key in (catname or '').lower() or key in noun:
                add(6, ph)
                break
        d = None
        raw = (prm.get('Діаметр') or '').replace(',', '.')
        if raw.replace('.', '').isdigit():
            d = float(raw)
            if d < 100:            # ще не нормалізовано — сантиметри
                d *= 10
        if d:
            for lim, lvl in LEVEL_BY_DIAMETER:
                if d <= lim:
                    if lvl:
                        add(6, f'{noun} {lvl}')
                    break
        if mat:
            for key, forms in MATERIAL_ADJ.items():
                if key in mat:
                    add(6, f'{agree(forms, noun)} {noun}')
                    break
        if color in COLOR_ADJ:
            add(6, f'{agree(COLOR_ADJ[color], noun)} {noun}')

    return list(slots)[:MAX_SLOTS]


def txt(o, tag):
    e = o.find(tag)
    return (e.text or '').strip() if e is not None else ''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sample', type=int, default=0)
    ap.add_argument('--report', action='store_true')
    a = ap.parse_args()

    root = ET.parse(FEED).getroot()
    cats = {c.get('id'): (c.text or '') for c in root.findall('.//category')}
    offers = root.findall('.//offer')

    old_all, new_all = collections.Counter(), collections.Counter()
    old_cnt, new_cnt = [], []
    contra_old = contra_new = 0
    shown = 0
    for o in offers:
        prm = {p.get('name'): (p.text or '') for p in o.findall('param')}
        name = txt(o, 'name_ua')
        desc = re.sub(r'<[^>]+>', ' ', txt(o, 'description_ua'))
        new = build(name, txt(o, 'vendor'), cats.get(txt(o, 'categoryId'), ''), prm, desc)
        old = [x.strip() for x in txt(o, 'keywords_ua').split(',') if x.strip()]
        purpose = (prm.get('Призначення') or '').lower()
        contra_old += sum(1 for p in old if contradicts(p, purpose))
        contra_new += sum(1 for p in new if contradicts(p, purpose))
        for p in old:
            old_all[p] += 1
        for p in new:
            new_all[p] += 1
        old_cnt.append(len(old)); new_cnt.append(len(new))
        if a.sample and shown < a.sample and len(new) >= 5:
            print('=' * 92)
            print(name)
            print('  БУЛО :', ', '.join(old))
            print('  СТАЛО:', ', '.join(new))
            shown += 1

    if a.report or not a.sample:
        def uniq(c):
            return f'{len(c)} унікальних на {sum(c.values())} вживань ' \
                   f'({100 * len(c) // max(1, sum(c.values()))} %)'
        print(f'\nтоварів: {len(offers)}')
        print(f'  БУЛО : {uniq(old_all)}; фраз на товар у середньому '
              f'{sum(old_cnt)/max(1,len(old_cnt)):.1f}')
        print(f'  СТАЛО: {uniq(new_all)}; фраз на товар у середньому '
              f'{sum(new_cnt)/max(1,len(new_cnt)):.1f}')
        print(f'  суперечностей із «Призначенням»: було {contra_old} → стало {contra_new}')
        print(f'  товарів із < {MIN_SLOTS} фраз: було '
              f'{sum(1 for x in old_cnt if x < MIN_SLOTS)} → стало '
              f'{sum(1 for x in new_cnt if x < MIN_SLOTS)}')
        print('\n  найчастіші фрази ПІСЛЯ:')
        for p, v in new_all.most_common(8):
            print(f'    {v:5}  {p}')


if __name__ == '__main__':
    main()
