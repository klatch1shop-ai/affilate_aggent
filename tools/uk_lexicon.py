#!/usr/bin/env python3
"""Ознака російської мови на словнику, а не на переліку основ.

Дві попередні версії ознаки були ручним переліком основ і провалились
однаково — і хибно тривожили, і недобирали. 25.08.2026 незалежна перевірка
показала третій провал того самого підходу: самоперевірка генератора звітувала
«назв характеристик російською: 0», тоді як у фіді лежали «Рабочий профиль»
(790 вживань), «Расход воздуха» (322), «Пневматический» (283), «двухсторонний»
(226).

Причина не в конкретному переліку. Російські слова без орфографічних позначок —
«набор», «нет», «ключи», «металл», «класс», «воздух», «сеть», «нож», «звезда» —
пишуться літерами, допустимими в українській, і жоден регекс їх не відрізнить.
Тому рішення приймає СЛОВНИК:

    1. є ы/э/ъ/ё            → російське (українська абетка їх не має);
    2. є в українському словнику (1.55 млн словоформ) → українське;
    3. є в лексиконі російських слів каталогу         → російське;
    4. закінчення, якого українська словозміна не утворює → російське;
    5. інакше                                          → НЕПІЗНАНЕ.

Порядок важливий: словник стоїть ПЕРЕД закінченнями, тому «герой», «алое»,
«ширина», «рукоятка» не можуть дати хибної тривоги — вони відсіюються на
кроці 2, не доходячи до морфології.

Кошик «непізнане» — не недолік, а вимога правила позитивного контролю: доки
він друкується поруч із нулем, «0 російських» не можна прочитати як «фід
чистий». Туди осідають суржик і одруківки («трещотковий», «сквозних»,
«крутючий», «бескамерних»), які не є ані російськими, ані правильними
українськими.

Дані: `data/uk_wordforms.txt.gz` (пакет wukrainian) і
`data/toptul_ru_lexicon.txt`, обидва збирає `tools/uk_lexicon_build.py`.
Якщо файлів немає — модуль ПАДАЄ, а не працює впівсили: ознака, яка мовчки
перестала знаходити, гірша за відсутню (саме так 22.08 «прогін завершився»
дорівняло «переклад зроблено» при 41 помилці HTTP 401).
"""
import gzip
import os
import re

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UK_FILE = os.path.join(BASE_DIR, 'data', 'uk_wordforms.txt.gz')
RU_FILE = os.path.join(BASE_DIR, 'data', 'toptul_ru_lexicon.txt')

# Апостроф усередині слова частина слова, а не межа: без цього «об'єму»
# розпадається на «об» і «єму», і обидва уламки лягають у «непізнане».
APOS = "ʼ'’`"
_TOKEN = re.compile(r"[а-яіїєґёыэъ]+(?:[" + APOS + r"][а-яіїєґ]+)*", re.I)

# Літери, яких українська абетка не має. Єдина ознака, що не потребує словника.
_ALIEN = re.compile(r'[ыэъё]')

# Закінчення, яких українська словозміна не утворює (укр. -ія, -ення, -ість,
# -ічний). Застосовуються ЛИШЕ до слів, яких немає в українському словнику,
# тому можуть бути коротшими й простішими, ніж у попередніх версіях.
# Мінімальна основа 3 літери для -ое і -ой: на двох туди потрапляють
# українські «алое» і «герой» — вони, щоправда, є й у словнику, але
# запобіжник лишається на випадок словоформи, якої в словнику немає.
_RU_END = re.compile(
    r'(?:'
    r'[а-яіїєґ]{2,}(?:ие|ия|ая|ость|ости)'
    r'|[а-яіїєґ]{3,}(?:ое|ой)'
    r'|[а-яіїєґ]{2,}ическ[а-я]*'
    r')$', re.I)

# Російські КОРЕНІ, узяті з постановки задачі власника від 25.08. Вони теж
# застосовуються лише до слів поза українським словником, і саме тому їх
# можна тримати короткими: український відповідник пишеться інакше
# (`різьб`, `викрут`, `робоч`, `витрат`, `двосторон`) і до цієї перевірки
# просто не доходить — його знімає словник.
#
# Корінь потрібен окремо від лексикона тому, що суржикові гібриди
# нескінченні: «резьбових», «Електроотвертка», «отверточних», «пневмоотвертка»
# — український префікс і закінчення на російському корені. Перелічувати їх
# словоформами означало б доганяти кожну нову; корінь ловить усі.
_RU_STEM = re.compile(
    r'рабоч|расход|резьб|отверт|двухстор|двустор|трещот|трещет'
    r'|съемник|удлинит|размер|материал|количеств|отверст|смазк|шлиц',
    re.I)

_uk: set | None = None
_ru: set | None = None


def _load() -> None:
    global _uk, _ru
    if _uk is not None:
        return
    if not os.path.exists(UK_FILE):
        raise FileNotFoundError(
            f'{UK_FILE} немає. Ознака російської без словника не працює. '
            f'Зібрати: python3 tools/uk_lexicon_build.py (потрібен пакет '
            f'wukrainian, /usr/share/dict/ukrainian)')
    with gzip.open(UK_FILE, 'rt', encoding='utf-8') as f:
        _uk = {w.strip() for w in f if w.strip()}
    if len(_uk) < 500_000:
        raise ValueError(f'{UK_FILE}: лише {len(_uk)} словоформ — файл обірваний')
    _ru = set()
    if os.path.exists(RU_FILE):
        with open(RU_FILE, encoding='utf-8') as f:
            _ru = {w.strip() for w in f
                   if w.strip() and not w.startswith('#')}


def sizes() -> tuple[int, int]:
    """Розміри обох словників — друкуються поруч із заміром, щоб нуль при
    порожньому словнику не читався як чистий фід."""
    _load()
    return len(_uk), len(_ru)


def norm(w: str) -> str:
    w = w.lower()
    for a in APOS[1:]:
        w = w.replace(a, 'ʼ')
    return w


def tokens(s: str) -> list[str]:
    return [norm(w) for w in _TOKEN.findall(s or '')]


def classify(word: str) -> str:
    """'ru' | 'uk' | 'unknown' для одного слова."""
    _load()
    w = norm(word)
    if len(w) < 3:
        return 'uk'          # прийменники, одиниці, уламки — не мовний сигнал
    if _ALIEN.search(w):
        return 'ru'
    if w in _uk:
        return 'uk'
    if w in _ru:
        return 'ru'
    if _RU_END.search(w) or _RU_STEM.search(w):
        return 'ru'
    return 'unknown'


def ru_words(s: str) -> list[str]:
    """Слова, про які СКАЗАНО, що вони російські."""
    return [w for w in tokens(s) if classify(w) == 'ru']


def unknown_words(s: str) -> list[str]:
    """Поза обома словниками: суржик, одруківки, нові терміни."""
    return [w for w in tokens(s) if classify(w) == 'unknown']


def is_ru(s: str) -> bool:
    return bool(ru_words(s))


def needs_translation(s: str) -> bool:
    """Відбір рядків на переклад. Тут ціна помилки протилежна заміру: зайвий
    український рядок у партії коштує кількох токенів, пропущений російський
    лишається у фіді назавжди, — тому непізнані теж беруться."""
    return any(classify(w) in ('ru', 'unknown') for w in tokens(s))
