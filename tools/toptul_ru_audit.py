#!/usr/bin/env python3
"""Незалежний замір російських залишків у готовому фіді TOPTUL.

Навіщо окремий інструмент, якщо генератор і сам друкує самоперевірку. Саме
тому й потрібен: 25.08.2026 самоперевірка генератора рапортувала «назв
характеристик російською: 0», а у фіді лежало 10 різних російських назв на
1189 вживань. Замір, вбудований у те, що він міряє, не має незалежного
свідка — і збрехав тричі поспіль (21.08, 22.08, 25.08).

Тому тут ДВІ перевірки з різними джерелами істини, і вони друкуються поруч:

  --patterns  жорсткий перелік ознак із постановки задачі власника:
              [ыъэё], «рабоч», «расход», «резьб», «отверт», «двухстор»,
              «-ический/-ный/-ная/-ные». Нічого не знає про наші словники,
              тому не може «погодитись» з ними через спільну помилку.
  --lexicon   словникова ознака (`tools/uk_lexicon.py`) — 1.55 млн українських
              словоформ плюс лексикон російських слів каталогу.

Перша — вужча й груба, друга — ширша. Правильний стан: усе, що знайшла
перша, знаходить і друга. Розбіжність у ЦЕЙ бік означає дефект ознаки, і
скрипт завершується кодом 1.

Читає фід XML напряму. Генератор не імпортується свідомо.

  python3 tools/toptul_ru_audit.py output/toptul_rozetka.xml
  python3 tools/toptul_ru_audit.py output/toptul_rozetka.xml --unknown
  python3 tools/toptul_ru_audit.py --selftest
"""
import argparse
import collections
import os
import re
import sys
import xml.etree.ElementTree as ET

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(BASE_DIR, 'tools'))

import uk_lexicon as LEX  # noqa: E402

# Перелік із постановки задачі, слово в слово. `-ний/-ная/-ные` подані ЧЕРЕЗ
# `-ный`, а не `-ний`: українське «шестигранний», «силовий», «накидний»
# закінчуються так само на -ний, і взяти його дослівно означало б порахувати
# півфіду. `-ный` російське однозначно (в укр. відповідає -ний), і саме воно
# ловить «двухсторонний», «односторонний», «внешний».
PATTERNS = re.compile(
    r'[ыъэё]'
    r'|рабоч'
    r'|расход'
    r'|резьб'
    r'|отверт'
    r'|двухстор'
    r'|[а-яіїєґ]{2,}(?:ический|ическая|ическое|ические|ный|ная|ные)\b',
    re.I)

# Власні назви не перекладають, тож і в замір вони не входять: «Бренд: Молния»
# вимагав би виправити те, що виправляти заборонено, і нуля не було б ніколи.
BRAND_PARAMS = ('Бренд', 'Виробник', 'Країна-виробник', 'Модель',
                'Країна-виробник товару')


def strip_article(title: str, article: str) -> str:
    """Артикул із назви геть — з тієї самої причини, що й BRAND_PARAMS.

    `build_name()` дописує артикул у дужках наприкінці, і береться він з тега
    `<article>`, а не з тексту назви, тобто перекладом його не змінити взагалі.
    Серед артикулів TOPTUL є написані кирилицею («ЭКСТРХ», «РАЗВ9.00»), і
    `Э` — чужа для української літера, тож замір рахував такий товар
    російським НАЗАВЖДИ. Це той самий випадок, що «Бренд: Молния» 23.08: мета,
    якої не можна досягти, бо досягати її заборонено правилом «бренди, моделі,
    артикули НЕ перекладай».

    Береться саме тег, а не «останні дужки»: у назвах є й змістовні дужки
    («(з фіксацією)», «(12-гр.)»), і вирізати їх означало б заплющити очі на
    справжні російські слова всередині.
    """
    return title.replace(f'({article})', ' ') if article else title


def strip_vendor(title: str, vendor: str) -> str:
    """Бренд, дописаний `build_name()` у хвіст назви, — теж не привід.

    Той самий випадок, що `strip_article()` і «Бренд: Молния» 23.08:
    `build_name()` бере бренд із тега `<vendor>` і додає його наприкінці, тож
    перекладом його не змінити, а перекладати бренди заборонено. Через це
    товари брендів «Молния» (3) і «Дальнобойщик» (1) рахувались російськими
    НАЗАВЖДИ, хоч самі назви давно українські.

    Знімається ЛИШЕ хвостове входження, а не всі: бренд буває звичайним
    словом, і вирізати його всюди означало б осліпнути на справжнє російське
    слово в тілі назви. Викликати після `strip_article()` — артикул стоїть
    ще правіше.
    """
    if not vendor:
        return title
    t = title.rstrip()
    return t[:-len(vendor)] if t.endswith(vendor) else title


def scan(path: str):
    root = ET.parse(path).getroot()
    res = {k: collections.Counter() for k in
           ('pat_name', 'pat_value', 'lex_name', 'lex_value',
            'unk_name', 'unk_value', 'pat_title', 'lex_title')}
    offers = 0
    for off in root.iter('offer'):
        offers += 1
        title = off.findtext('name_ua') or off.findtext('name') or ''
        title = strip_article(title, (off.findtext('article') or '').strip())
        title = strip_vendor(title, (off.findtext('vendor') or '').strip())
        if PATTERNS.search(title):
            res['pat_title'][title] += 1
        if LEX.is_ru(title):
            res['lex_title'][title] += 1
        for p in off.findall('param'):
            k = (p.get('name') or '').strip()
            if PATTERNS.search(k):
                res['pat_name'][k] += 1
            if LEX.is_ru(k):
                res['lex_name'][k] += 1
            for w in LEX.unknown_words(k):
                res['unk_name'][w] += 1
            if k in BRAND_PARAMS:
                continue
            # Багатозначний параметр Rozetka — одне поле, значення через <br>.
            for v in re.split(r'<br\s*/?>', p.text or ''):
                v = v.strip()
                if not v:
                    continue
                if PATTERNS.search(v):
                    res['pat_value'][v] += 1
                if LEX.is_ru(v):
                    res['lex_value'][v] += 1
                for w in LEX.unknown_words(v):
                    res['unk_value'][w] += 1
    return offers, res


def _show(title, c, top=15):
    print(f'{title}: {len(c)} різних, {sum(c.values())} вживань')
    for s, n in c.most_common(top):
        print(f'   {n:5}  {s[:80]}')


def selftest() -> int:
    """Позитивний контроль: перевірка, яка нічого не ловить, дає нуль, не
    помиляючись. Кожен рядок ліворуч відрізняється від правого лише мовою."""
    ru = ['Рабочий профиль', 'Расход воздуха', 'Пневматический',
          'двухсторонний', 'Гидравлический', 'набор отверток',
          'Крок резьби', 'Металлический кейс', 'Конический',
          'Динамометрический', 'Тип шлица', 'Маркировка наконечника',
          'Монитор', 'Набор ключей', 'Подсветка дисплея', 'Глубина',
          'Тип мебели', 'Тип аккумулятора', 'Шкала измерений', 'нет',
          'Регулировка количества оборотов', 'Тип двигателя', 'Механизм',
          'Устройство накачки шин', 'Тип ножниц по металлу', 'Монтировка',
          'Ширина зажима', 'Материал изделия', 'Питание', 'Состояние']
    uk = ['Робочий профіль', 'Витрата повітря', 'Пневматичний',
          'двосторонній', 'Гідравлічний', 'набір викруток',
          'Крок різі', 'Металевий кейс', 'Конічний', 'Динамометричний',
          'Тип шліца', 'Маркування наконечника', 'Монітор', 'Набір ключів',
          'Підсвітка дисплея', 'Глибина', 'Тип меблів', 'Тип акумулятора',
          'Шкала вимірювань', 'ні', 'Регулювання кількості обертів',
          'Тип двигуна', 'Механізм', 'Пристрій накачування шин',
          'Тип ножиць по металу', 'Монтувалка', 'Ширина затиску',
          'Матеріал виробу', 'Живлення', 'Стан',
          # ті, на яких хибно спрацьовували ПОПЕРЕДНІ версії ознаки
          'Ширина', 'Матеріал рукоятки', 'Вид приводу інструмента',
          'Передаточне число', 'Шестигранник', 'Ключ шестигранний',
          'Максимальний крутний момент', 'Діаметр коліс', 'алое', 'герой',
          'Головка торцева', 'Набір ключів', 'Довжина рукоятки']
    bad = 0
    for s in ru:
        if not LEX.is_ru(s):
            print(f'  НЕ впізнано російське: {s!r} '
                  f'(непізнані слова: {LEX.unknown_words(s)})')
            bad += 1
    for s in uk:
        hit = LEX.ru_words(s)
        if hit:
            print(f'  ХИБНА тривога на українському: {s!r} через {hit}')
            bad += 1
    uk_n, ru_n = LEX.sizes()
    print(f'словники: {uk_n} укр. словоформ, {ru_n} рос. слів')
    if bad:
        print(f'САМОПЕРЕВІРКА: {bad} розбіжностей')
    else:
        print(f'САМОПЕРЕВІРКА: {len(ru)} російських впізнано, '
              f'0 хибних на {len(uk)} українських')
    return bad


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('feed', nargs='?',
                    default=os.path.join(BASE_DIR, 'output',
                                         'toptul_rozetka.xml'))
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('--unknown', action='store_true',
                    help='друкувати кошик непізнаних слів')
    ap.add_argument('--top', type=int, default=15)
    a = ap.parse_args()

    if a.selftest:
        return 1 if selftest() else 0

    offers, r = scan(a.feed)
    uk_n, ru_n = LEX.sizes()
    print(f'{a.feed}: {offers} офферів')
    print(f'словники: {uk_n} укр. словоформ, {ru_n} рос. слів\n')

    print('── перевірка 1: перелік ознак із постановки ──')
    _show('  назви характеристик', r['pat_name'], a.top)
    _show('  значення характеристик', r['pat_value'], a.top)
    _show('  назви товарів', r['pat_title'], 5)

    print('\n── перевірка 2: словникова ознака ──')
    _show('  назви характеристик', r['lex_name'], a.top)
    _show('  значення характеристик', r['lex_value'], a.top)
    _show('  назви товарів', r['lex_title'], 5)

    if a.unknown:
        print('\n── непізнані слова (суржик, одруківки, нові терміни) ──')
        _show('  у назвах характеристик', r['unk_name'], 60)
        _show('  у значеннях', r['unk_value'], 60)

    # Головне твердження цього скрипта. Словникова ознака мусить бути
    # НАДмножиною грубого переліку; інакше вона знову недобирає.
    rc = 0
    for kind in ('name', 'value', 'title'):
        gap = {s: n for s, n in r[f'pat_{kind}'].items()
               if s not in r[f'lex_{kind}']}
        if gap:
            rc = 1
            print(f'\nДЕФЕКТ ОЗНАКИ: перелік знайшов у "{kind}" {len(gap)} '
                  f'рядків, яких словникова ознака НЕ бачить:')
            for s, n in sorted(gap.items(), key=lambda x: -x[1])[:20]:
                print(f'   {n:5}  {s[:80]}')
    if not rc:
        print('\nЗБІГ: словникова ознака знаходить усе, що знаходить перелік.')
    return rc


if __name__ == '__main__':
    sys.exit(main())
