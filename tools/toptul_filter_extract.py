def load_llm(path: str = None) -> dict:
    """Значення, підібрані моделлю (`tools/toptul_llm_filters.py`).

    Це **дані, а не код**: їх видно у файлі, їх можна переглянути очима й
    виправити. Модель обирала виключно зі списку значень довідника Rozetka,
    і кожне значення тут ще раз проходить `_keep_known` нижче — тож у фід
    не потрапить нічого, чого немає в довіднику категорії.

    Джерело найнижчого пріоритету: спершу характеристика постачальника,
    потім правило за назвою, потім головне слово, і лише тоді модель.
    """
    global _LLM_CACHE
    if _LLM_CACHE is None:
        try:
            with open(path or LLM_FILE, encoding='utf-8') as f:
                _LLM_CACHE = json.load(f)
        except Exception:
            _LLM_CACHE = {}
    return _LLM_CACHE


def extract(rz_id: str, params: dict, product_name: str, ref: dict,
            sku: str = None) -> dict:
    """{назва характеристики: {values, valueids, paramid, source, dropped}}.

    `params` — {назва: [значення]}, як його віддає `collect_params`.
    Категорії, у довіднику якої такої характеристики немає, не чіпаємо взагалі.
    """
    cat = ref.get(str(rz_id)) or {}
    out = {}

    slot = cat.get(SQUARE)
    if slot and SQUARE not in params:
        vals, source = [], 'param'
        for pname in SQUARE_PARAMS:
            for raw in params.get(pname, []):
                for v in squares_in(raw):
                    if v not in vals:
                        vals.append(v)
        if not vals:
            vals, source = squares_in(product_name, first_only=True), 'name'
        kept, dropped = _keep_known(vals, slot)
        if kept:
            out[SQUARE] = {'values': kept, 'paramid': slot['paramid'],
                           'valueids': [slot['values'][v] for v in kept],
                           'source': source, 'dropped': dropped}

    slot = cat.get(FACES)
    if slot and FACES not in params:
        vals, source = [], 'param'
        for raw in params.get('Робочий профіль', []):
            v = PROFILE_TO_FACES.get(str(raw).strip().lower())
            if v and v not in vals:
                vals.append(v)
        if not vals:
            vals, source = faces_in(product_name), 'name'
        kept, dropped = _keep_known(vals, slot)
        if kept:
            out[FACES] = {'values': kept, 'paramid': slot['paramid'],
                          'valueids': [slot['values'][v] for v in kept],
                          'source': source, 'dropped': dropped}

    # ── друга черга ───────────────────────────────────────────────────────
    slot = cat.get(WORKSIZE)
    if slot and WORKSIZE not in params and not is_set(params, product_name):
        _emit(out, slot, WORKSIZE, sizes_in(params), 'param')

    for attr in (VIEW, KIND, FEATURES):
        slot = cat.get(attr)
        if slot and attr not in params:
            vals, source = _by_rules(rz_id, attr, params, product_name)
            if not vals:
                vals = _by_head_noun(slot, product_name)
                source = 'head' if vals else source
            if not vals and sku:
                v = (load_llm().get(str(sku)) or {}).get(attr)
                if v:
                    vals, source = [v], 'llm'
            if vals:
                _emit(out, slot, attr, vals, source)

    slot = cat.get(FEATURES)
    if slot and FEATURES not in params:
        low = (product_name or '').lower()
        vals = [v for pat, v in FEATURE_RE if re.search(pat, low)]
        if vals:
            _emit(out, slot, FEATURES, vals, 'name')
    return out


