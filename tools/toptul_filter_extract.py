def load_reference(path: str = REF_FILE) -> dict:
    if not os.path.exists(path):
        raise FileNotFoundError(
            f'Немає довідника значень Rozetka: {path}. '
            f'Зібрати: python3 tools/rozetka_option_ids.py')
    return json.load(open(path, encoding='utf-8'))


def _keep_known(values, slot):
    """Лишити тільки те, що є в довіднику категорії, у його ж порядку."""
    known = slot['values']
    order = list(known)
    kept = [v for v in values if v in known]
    dropped = [v for v in values if v not in known]
    kept.sort(key=order.index)
    return kept, dropped


def _emit(out: dict, slot: dict, name: str, values, source: str):
    """Спільний вихід для всіх характеристик: whitelist, id, `dropped`.

    Один вихід, а не п'ять — щоб запобіжник «лише значення з довідника» не
    треба було повторювати в кожному видобувачі: пропущений повтор і є той
    спосіб, яким вигадане значення потрапляє у фід.
    """
    kept, dropped = _keep_known(values, slot)
    # `ComboBox` — одне значення; `List`/`ListValues` — скільки є. Зрізане
    # тут НЕ те саме, що `dropped`, і мішати їх не можна: `dropped` — це
    # значення, якого в довіднику Rozetka немає (сигнал, що правило вигадує),
    # а `trimmed` — правильне значення, яке просто не вміщається в одиничний
    # вибір. Одна купа зробила б перший сигнал нечитаним.
    trimmed = []
    if kept and str(slot.get('attr_type')) == 'ComboBox':
        first = next(v for v in values if v in kept)
        trimmed = [v for v in kept if v != first]
        kept = [first]
    if kept:
        out[name] = {'values': kept, 'paramid': slot['paramid'],
                     'valueids': [slot['values'][v] for v in kept],
                     'source': source, 'dropped': dropped, 'trimmed': trimmed}


def _by_head_noun(slot: dict, product_name: str) -> list:
    """«Тип»/«Вид» за ПЕРШИМ словом назви, коли явного правила для категорії
    немає.

    Постачальник називає товар тим, чим той є: «Знімач підшипників…»,
    «Набір знімачів…», «Ключ храповика…». Довідник Rozetka для «Знімачів»
    має рівно ці три значення, тож головне слово назви і є відповіддю.
    Так закривається 276 офферів, для яких окремих правил ніхто не писав.

    Свідомо перевіряємо **лише перше слово**, а не всю назву. «Знімач
    рульових наконечників» містить слово «ключ» далі в описі, а «Ремонтний
    комплект для фарбопультів» — слово «комплект», яке в довіднику означає
    *комплект для чищення*. Обидва випадки дали б хибне значення. Коли перше
    слово ні з чим не збігається, значення просто не виставляється: пропуск
    дешевший за помилку (правило 5 черги).
    """
    words = re.findall(r'[А-Яа-яІіЇїЄєҐґA-Za-z]{4,}', product_name or '')
    if not words:
        return []
    head = words[0].lower()
    for val in slot.get('values', {}):
        core = re.split(r'[\s/,]', val.strip().lower())[0]
        if len(core) < 5 or len(head) < 5:
            continue
        n = min(len(core), len(head), 8)
        if core[:n] == head[:n]:
            return [val]
    return []


def _by_rules(rz_id: str, attr: str, params: dict, product_name: str) -> tuple:
    """Значення за таблицею `RULES`: перше джерело, яке щось дало.

    Джерела перебираються в порядку, записаному в самому правилі, — саме
    тому порядок і винесено в дані, а не зашито тут.
    """
    low = (product_name or '').lower()
    for kind, spec in RULES.get((str(rz_id), attr)) or ():
        vals = []
        if kind == 'param':
            for pname, mapping in spec.items():
                for raw in params.get(pname, []):
                    v = mapping.get(str(raw).strip().lower())
                    if v and v not in vals:
                        vals.append(v)
        else:
            for pat, v in spec:
                if re.search(pat, low) and v not in vals:
                    vals.append(v)
        if vals:
            return vals, kind
    return [], 'rule'


