#!/usr/bin/env python3
"""Дві фільтрові характеристики Rozetka, яких у фіді TOPTUL немає:
«Розмір посадкового квадрата» і «Кількість граней».

Зауваження Rozetka #7253098 п.3 (24.08.2026): без параметрів, які є фільтрами
категорії, товар не потрапляє у відфільтровану вибірку покупця. Обидві
характеристики — головні фільтри своїх категорій, і в жодного нашого оффера
їх немає.

ЗВІДКИ БЕРЕТЬСЯ ЗНАЧЕННЯ, І ЧОМУ НЕ З НАЗВИ
--------------------------------------------
Постановка задачі казала «обидва є прямо в назвах». Це правда, але назва —
НЕ надійне джерело, і замір це показав перш ніж рядок коду було написано:

    Головка торцева ударна 1/2" дюймова 5/8" Toptul (KBBA1620)

Тут `1/2"` — посадковий квадрат, а `5/8"` — розмір самої головки в дюймах.
Правило «взяти всі дюймові позначки з назви» приписало б головці квадрат
5/8", якого не буває. Те саме в наборах: `Набір головок дюймових ударних
довгих 1/2" 7/16-1" 10 од.` — `7/16-1"` це діапазон розмірів головок.
Таких офферів у фіді 15, і всі 15 виявились би зіпсованими.

Тому порядок джерел зворотний до постановки:

1. **Характеристика постачальника** — «Квадрат» (772 вживання),
   «Приєднувальний квадрат» (58), «Розмір приєднувальних головок» (217),
   «Вхідний/Вихідний квадрат» (по 6). Тут значення означає рівно те, що
   треба, і кілька значень у ньому — теж факт (перехідник 3/4"х1-1/2").
2. **Назва — лише як запасний шлях і лише ПЕРШИЙ дюймовий токен.** У назвах
   інструмента посадковий квадрат стоїть першим, а розмір робочої частини —
   після нього. Дає 34 оффери, яких немає в п.1; усі 34 перевірені очима.

Для «Кількості граней» так само: спершу «Робочий профіль» постачальника
(Шестигранник → Шестигранні), і лише за його відсутності — назва
(«Головка 8-гранна 85 мм під монтувалку»).

ЗАПОБІЖНИК ВІД ВИГАДАНОГО ЗНАЧЕННЯ
-----------------------------------
Назовні виходить лише те значення, яке Є в довіднику категорії Rozetka
(`data/rozetka_filter_values.json`, збирає `rozetka_option_ids.py`), разом із
його `valueid`. Це не формальність, а третій запобіжник: `1-1/8"`, `5/8"`,
`7/16"` у довіднику відсутні, тож навіть якби вони прослизнули з назви,
у фід вони не потраплять. Правило 5 черги («не вигадувати значення») тут
виконується самою побудовою, а не уважністю.

    python3 tools/toptul_filter_extract.py --selftest
    python3 tools/toptul_filter_extract.py --feed output/toptul_rozetka.xml
"""
import argparse
import collections
import json
import os
import re
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF_FILE = os.path.join(BASE_DIR, 'data', 'rozetka_filter_values.json')

SQUARE = 'Розмір посадкового квадрата'
FACES = 'Кількість граней'

# Характеристики постачальника, які несуть посадковий квадрат. Назви — уже
# ПЕРЕКЛАДЕНІ (`collect_params` застосовує `toptul_translation` до того, як
# сюди потрапить), тому перелік звірено з готовим фідом, а не з сирим.
SQUARE_PARAMS = ('Квадрат', 'Приєднувальний квадрат',
                 'Розмір приєднувальних головок',
                 'Вхідний квадрат', 'Вихідний квадрат', 'Приєдний квадрат:')

# Дюймова позначка. `''` (два апострофи) — не примха: у назві
# `Набір інструменту 17-65 мм 3/4'' 1" 26 од.` квадрат записаний саме так, і
# без цієї гілки перший токен зчитався б як `1`, тобто хибно.
_INCH = r'(?:"|”|″|\'\'|’’|\s*дюйм\w*)'
# Зліва — не цифра й не дріб, інакше `16` у `7/16-1"` дало б свій «токен».
# Мішаний дріб пишуть і через дефіс (`1-1/2"`, назви), і через пробіл
# (`1 1/2"`, характеристика «Вихідний квадрат»). Обидві гілки стоять ПЕРЕД
# простим дробом: інакше `1 1/2"` розібралось би як `1/2` — саме так
# самоперевірка й упіймала першу редакцію цього регекса.
_SQUARE_RE = re.compile(
    r'(?<![\d/.,])(\d\s*[-–]\s*\d/\d|\d\s+\d/\d|\d/\d|\d)\s*' + _INCH)

# «Робочий профіль» постачальника → значення довідника Rozetka. Профілі, яких
# у переліку немає (TORX, Spline, Зірка (Е-профіль), PH, PZ, Навісний,
# П'ятигранник — 132 оффери), свідомо лишаються без значення: «кількість
# граней» до них не застосовна, а підставити найближче означало б збрехати.
PROFILE_TO_FACES = {
    'шестигранник': 'Шестигранні',
    'дванадцятигранник': 'Дванадцятигранні',
    'восьмигранник': 'Восьмигранні',
    'чотиригранник': 'Чотиригранні',
    'квадрат': 'Чотиригранні',
}
_NUM_TO_FACES = {'4': 'Чотиригранні', '6': 'Шестигранні',
                 '8': 'Восьмигранні', '12': 'Дванадцятигранні'}
_WORD_TO_FACES = {'чотиригран': 'Чотиригранні', 'шестигран': 'Шестигранні',
                  'восьмигран': 'Восьмигранні',
                  'дванадцятигран': 'Дванадцятигранні'}
# Скорочення `гр.` вимагає дефіса (`12-гр.`), бо без нього під нього підпадає
# вага: `500 гр.` — не дванадцять граней і не п'ятсот.
_FACES_RE = re.compile(
    r'(\d{1,2})\s*(?:[-–]\s*гран|\s*гран|[-–]\s*гр\.)'
    r'|(чотиригран|шестигран|восьмигран|дванадцятигран)', re.I)


def _norm_square(tok: str) -> str:
    """`1-1/2` → `1 1/2`: у довіднику Rozetka ціла частина відділена пробілом."""
    tok = re.sub(r'\s+', ' ', tok.strip()).replace('–', '-')
    return re.sub(r'^(\d)\s*-\s*(\d/\d)$', r'\1 \2', tok)


def squares_in(text: str, first_only: bool = False) -> list:
    out = []
    for m in _SQUARE_RE.finditer(text or ''):
        v = _norm_square(m.group(1))
        if v not in out:
            out.append(v)
        if first_only:
            break
    return out


def faces_in(text: str) -> list:
    out = []
    for m in _FACES_RE.finditer(text or ''):
        v = (_NUM_TO_FACES.get(m.group(1)) if m.group(1)
             else _WORD_TO_FACES.get(m.group(2).lower()))
        if v and v not in out:
            out.append(v)
    return out


def load_reference(path: str = REF_FILE) -> dict:
    if not os.path.exists(path):
        raise FileNotFoundError(
            f'Немає довідника значень Rozetka: {path}. '
            f'Зібрати: python3 tools/rozetka_option_ids.py')
    return json.load(open(path, encoding='utf-8'))


def _keep_known(values, slot):
    """Лишити тільки те, що є в довіднику категорії, у його ж порядку."""
    known = slot['values']
    order = list(known)
    kept = [v for v in values if v in known]
    dropped = [v for v in values if v not in known]
    kept.sort(key=order.index)
    return kept, dropped


def extract(rz_id: str, params: dict, product_name: str, ref: dict) -> dict:
    """{назва характеристики: {values, valueids, paramid, source, dropped}}.

    `params` — {назва: [значення]}, як його віддає `collect_params`.
    Категорії, у довіднику якої такої характеристики немає, не чіпаємо взагалі.
    """
    cat = ref.get(str(rz_id)) or {}
    out = {}

    slot = cat.get(SQUARE)
    if slot and SQUARE not in params:
        vals, source = [], 'param'
        for pname in SQUARE_PARAMS:
            for raw in params.get(pname, []):
                for v in squares_in(raw):
                    if v not in vals:
                        vals.append(v)
        if not vals:
            vals, source = squares_in(product_name, first_only=True), 'name'
        kept, dropped = _keep_known(vals, slot)
        if kept:
            out[SQUARE] = {'values': kept, 'paramid': slot['paramid'],
                           'valueids': [slot['values'][v] for v in kept],
                           'source': source, 'dropped': dropped}

    slot = cat.get(FACES)
    if slot and FACES not in params:
        vals, source = [], 'param'
        for raw in params.get('Робочий профіль', []):
            v = PROFILE_TO_FACES.get(str(raw).strip().lower())
            if v and v not in vals:
                vals.append(v)
        if not vals:
            vals, source = faces_in(product_name), 'name'
        kept, dropped = _keep_known(vals, slot)
        if kept:
            out[FACES] = {'values': kept, 'paramid': slot['paramid'],
                          'valueids': [slot['values'][v] for v in kept],
                          'source': source, 'dropped': dropped}
    return out


