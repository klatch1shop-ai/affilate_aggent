def selftest() -> int:
    bad = 0
    for rz, params, name, exp_sq, exp_fa, why in _CASES:
        got = extract(rz, params, name, _REF_SELFTEST)
        sq = got.get(SQUARE, {}).get('values', [])
        fa = got.get(FACES, {}).get('values', [])
        ok = sq == exp_sq and fa == exp_fa
        bad += not ok
        print(f'{"OK  " if ok else "ЗБІЙ"} [{rz}] {name[:52]:54} '
              f'кв={sq} гр={fa}' + ('' if ok
                                    else f'  ОЧІКУВАНО кв={exp_sq} гр={exp_fa}'))
        if not ok:
            print(f'       ← {why}')
    # Контроль самого контролю: серед випадків мусять бути й ті, де очікується
    # порожньо, інакше перелік доводить лише те, що перевірка щось знаходить.
    empties = sum(1 for c in _CASES if not c[3] and not c[4])
    print(f'\nвипадків: {len(_CASES)} (з них із порожнім очікуванням: '
          f'{empties}), збоїв: {bad}')
    return 1 if bad or empties < 3 else 0


def audit_feed(path: str, ref: dict) -> int:
    import xml.etree.ElementTree as ET
    root = ET.parse(path).getroot()
    rz = {c.get('id'): (c.get('rz_id'), (c.text or '').strip())
          for c in root.findall('.//categories/category')}
    per = collections.defaultdict(collections.Counter)
    dropped = collections.Counter()
    for o in root.findall('.//offer'):
        rz_id, rz_name = rz.get((o.findtext('categoryId') or '').strip(),
                                (None, ''))
        if not rz_id or rz_id not in ref:
            continue
        params = collections.defaultdict(list)
        for p in o.findall('param'):
            params[p.get('name')].append((p.text or '').strip())
        c = per[(rz_id, rz_name)]
        c['офферів'] += 1
        for pn in ref[rz_id]:
            if pn in params:
                c[f'{pn}: вже у фіді'] += 1
        got = extract(rz_id, params, o.findtext('name_ua') or '', ref)
        for pn, d in got.items():
            c[f'{pn}: з {d["source"]}'] += 1
            for v in d['dropped']:
                dropped[(rz_id, pn, v)] += 1
    for (rz_id, rz_name), c in sorted(per.items(), key=lambda x: -x[1]['офферів']):
        print(f'=== {rz_id} {rz_name} — {c["офферів"]} офферів')
        for k, v in sorted(c.items()):
            if k != 'офферів':
                print(f'    {v:6}  {k}')
    if dropped:
        print('\nзначення поза довідником Rozetka (не виводяться у фід):')
        for (rz_id, pn, v), n in dropped.most_common():
            print(f'   {n:5}  [{rz_id}] {pn} = {v!r}')
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--selftest', action='store_true')
    ap.add_argument('--feed')
    a = ap.parse_args()
    if a.selftest:
        sys.exit(selftest())
    if a.feed:
        sys.exit(audit_feed(a.feed, load_reference()))
    ap.error('потрібен --selftest або --feed')


if __name__ == '__main__':
    main()
