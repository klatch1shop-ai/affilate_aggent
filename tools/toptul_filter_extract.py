# Характеристики постачальника, які несуть посадковий квадрат. Назви — уже
# ПЕРЕКЛАДЕНІ (`collect_params` застосовує `toptul_translation` до того, як
# сюди потрапить), тому перелік звірено з готовим фідом, а не з сирим.
SQUARE_PARAMS = ('Квадрат', 'Приєднувальний квадрат',
                 'Розмір приєднувальних головок',
                 'Вхідний квадрат', 'Вихідний квадрат', 'Приєдний квадрат:')

# Дюймова позначка. `''` (два апострофи) — не примха: у назві
# `Набір інструменту 17-65 мм 3/4'' 1" 26 од.` квадрат записаний саме так, і
# без цієї гілки перший токен зчитався б як `1`, тобто хибно.
_INCH = r'(?:"|”|″|\'\'|’’|\s*дюйм\w*)'
# Зліва — не цифра й не дріб, інакше `16` у `7/16-1"` дало б свій «токен».
# Мішаний дріб пишуть і через дефіс (`1-1/2"`, назви), і через пробіл
# (`1 1/2"`, характеристика «Вихідний квадрат»). Обидві гілки стоять ПЕРЕД
# простим дробом: інакше `1 1/2"` розібралось би як `1/2` — саме так
# самоперевірка й упіймала першу редакцію цього регекса.
_SQUARE_RE = re.compile(
    r'(?<![\d/.,])(\d\s*[-–]\s*\d/\d|\d\s+\d/\d|\d/\d|\d)\s*' + _INCH)

# «Робочий профіль» постачальника → значення довідника Rozetka. Профілі, яких
# у переліку немає (TORX, Spline, Зірка (Е-профіль), PH, PZ, Навісний,
# П'ятигранник — 132 оффери), свідомо лишаються без значення: «кількість
# граней» до них не застосовна, а підставити найближче означало б збрехати.
PROFILE_TO_FACES = {
    'шестигранник': 'Шестигранні',
    'дванадцятигранник': 'Дванадцятигранні',
    'восьмигранник': 'Восьмигранні',
    'чотиригранник': 'Чотиригранні',
    'квадрат': 'Чотиригранні',
}
_NUM_TO_FACES = {'4': 'Чотиригранні', '6': 'Шестигранні',
                 '8': 'Восьмигранні', '12': 'Дванадцятигранні'}
_WORD_TO_FACES = {'чотиригран': 'Чотиригранні', 'шестигран': 'Шестигранні',
                  'восьмигран': 'Восьмигранні',
                  'дванадцятигран': 'Дванадцятигранні'}
# Скорочення `гр.` вимагає дефіса (`12-гр.`), бо без нього під нього підпадає
# вага: `500 гр.` — не дванадцять граней і не п'ятсот.
_FACES_RE = re.compile(
    r'(\d{1,2})\s*(?:[-–]\s*гран|\s*гран|[-–]\s*гр\.)'
    r'|(чотиригран|шестигран|восьмигран|дванадцятигран)', re.I)


def _norm_square(tok: str) -> str:
    """`1-1/2` → `1 1/2`: у довіднику Rozetka ціла частина відділена пробілом."""
    tok = re.sub(r'\s+', ' ', tok.strip()).replace('–', '-')
    return re.sub(r'^(\d)\s*-\s*(\d/\d)$', r'\1 \2', tok)


def squares_in(text: str, first_only: bool = False) -> list:
    out = []
    for m in _SQUARE_RE.finditer(text or ''):
        v = _norm_square(m.group(1))
        if v not in out:
            out.append(v)
        if first_only:
            break
    return out


def faces_in(text: str) -> list:
    out = []
    for m in _FACES_RE.finditer(text or ''):
        v = (_NUM_TO_FACES.get(m.group(1)) if m.group(1)
             else _WORD_TO_FACES.get(m.group(2).lower()))
        if v and v not in out:
            out.append(v)
    return out


