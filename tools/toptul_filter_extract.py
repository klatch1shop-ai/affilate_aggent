# нічого не псує, а порядок лишається читаним.
SIZE_PARAMS = ('Розмір min', 'Розмір max', 'Розмір')
# Ознака набору. Слово в назві + характеристики про кількість: жодна з них
# поодинці не покриває всього («Набір» без кількості, «12 предметів» без
# слова «набір»).
_SET_RE = re.compile(r'набір|набор|компл[еє]кт', re.I)
SET_PARAMS = ('Кількість у наборі', 'Кількість інструментів у наборі',
              'Кількість одиниць', 'Кількість предметів')
_PLAIN_NUM_RE = re.compile(r'^\d{1,3}(?:[.,]\d+)?$')


def _norm_num(s: str) -> str:
    """`12.0` → `12`, `5,5` → `5.5`: у довіднику Rozetka саме така форма."""
    s = s.strip().replace(',', '.')
    if '.' in s:
        s = s.rstrip('0').rstrip('.')
    return s or '0'


def is_set(params: dict, product_name: str) -> bool:
    return bool(_SET_RE.search(product_name or '')) or any(
        params.get(k) for k in SET_PARAMS)


def sizes_in(params: dict) -> list:
    # Роздільник значень тут `|` і `;`, але НЕ кома: у цих характеристиках
    # кома — десятковий роздільник (`Розмір max: 5,5`), і поділ по ній
    # перетворював один розмір 5.5 на два неіснуючі — 5 і 5. Упіймано
    # самоперевіркою до першого прогону на даних.
    out = []
    for pname in SIZE_PARAMS:
        for raw in params.get(pname, []):
            for part in re.split(r'[|;]', str(raw)):
                part = part.strip()
                if _PLAIN_NUM_RE.match(part):
                    v = _norm_num(part)
                    if v not in out:
                        out.append(v)
    return out


