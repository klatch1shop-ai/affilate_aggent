def build_name(raw_name: str, vendor: str, prm: dict, sku: str,
               rz_id: str = '') -> str:
    """Тип · Виробник · Модель · Розмір · Колір · (Артикул), без ком."""
    parts = []
    kind = prm.get('Тип') or prm.get('Вид') or CATEGORY_KIND.get(rz_id)
    if kind:
        parts.append(kind)
    if vendor:
        parts.append(vendor)                       # має збігатися з <vendor>
    model = _model_from(raw_name, vendor)
    if model and model.lower() != (kind or '').lower():
        parts.append(model)
    if size := size_label(raw_name, prm.get('Розмір')):
        parts.append(size)
    if volume := prm.get("Об'єм"):
        parts.append(volume)
    if color := prm.get('Колір'):
        parts.append(color)
    name = re.sub(r'\s+', ' ', ' '.join(p for p in parts if p)).strip()
    tail = f' ({sku})'
    if len(name) + len(tail) > MAX_NAME:
        name = name[:MAX_NAME - len(tail)].rsplit(' ', 1)[0]
    return (name + tail).replace(',', '')


def synth_description(name: str, prm: dict, vendor: str) -> str:
    """Короткий опис із назви та вже підтверджених характеристик."""
    brand = re.sub(r'\s*\(.*?\)', '', vendor or '').strip()
    head = DESC_TYPE_PHRASE.get(prm.get('Тип') or prm.get('Вид'), 'Виріб')
    parts = [f'{head} {brand}'.strip() if brand else head]

    detail = []
    if c := prm.get('Колір'):
        detail.append(f'{c.lower()} колір')
    if s := size_label(name, prm.get('Розмір')):
        detail.append(f'розмір {s}')
    if detail:
        parts.append(', '.join(detail))
    first = '. '.join([' — '.join(parts)]) if len(parts) > 1 else parts[0]

    out = [first + '.']
    if m := prm.get('Матеріал'):
        out.append(f'Матеріал — {m.lower()}.')
    feats = [DESC_FEATURE[k][v] for k, v in prm.items()
             if k in DESC_FEATURE and v in DESC_FEATURE[k]]
    if feats:
        out.append(f'Особливості моделі: {", ".join(feats)}.')
    if country := prm.get('Країна-виробник товару'):
        out.append(f'Країна виробництва — {country}.')
    return ' '.join(out)


def quantity_from_name(name: str):
    """Справжня кількість в упаковці з назви: «Презерватив …, 3 шт» → «3».

    Раніше тут стояла константа '1' для всіх товарів — вона тримала третю
    характеристику у 759 позицій, але нічого не повідомляла покупцеві й для
    презервативів була просто хибною: їх продають упаковками по 3, 12, 24.
    """
    m = re.search(r'(\d+)\s*(?:шт|предмет)', name, re.I)
    return m.group(1) if m else None


def _first_match(rules, text):
    for rx, val in rules:
        m = re.search(rx, text, re.I)
        if m:
            return val if val is not None else m.group(0).upper()
    return None


def params_from_name(text: str, rz_id: str, desc: str = '') -> dict:
    """Характеристики з назви; для окремих — ще й з опису.

    Опис читається лише для DESC_ALLOWED_PARAMS: у назвах цих ознак немає
    взагалі, а суцільне читання опису дає хибні спрацювання (панчохи
    діставали «З пажами для панчіх», бо опис радив, з чим їх носити).
    """
    out = {}
    for pname, rules in NAME_PARAM_RULES.get(rz_id, {}).items():
        val = _first_match(rules, text)
        if not val and desc and pname in DESC_ALLOWED_PARAMS:
            val = _first_match(rules, desc)
        if val:
            out[pname] = val
    return out


