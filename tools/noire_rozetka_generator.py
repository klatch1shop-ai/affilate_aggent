def _unit_candidates(v: str):
    """Голе число — у формах, які знає довідник Rozetka.

    Постачальник зберігає обʼєм числом без одиниці («100»), а довідник
    очікує «100 мл». Через це «Обʼєм» відкидався у всіх 514 лубрикантів —
    і саме цієї характеристики бракувало 395 з них до мінімальних трьох.
    Дробова частина теж записана по-різному: у нас «29,5», у них «29.5 мл».
    """
    m = re.fullmatch(r'(\d+(?:[.,]\d+)?)\s*(мл|ml|л|г|гр|g)?', v.strip(), re.I)
    if not m:
        return []
    num = m.group(1).replace(',', '.')
    if '.' in num:
        num = num.rstrip('0').rstrip('.')
    unit = (m.group(2) or '').lower()
    unit = {'ml': 'мл', 'гр': 'г', 'g': 'г'}.get(unit, unit)
    return [f'{num} {u}' for u in ([unit] if unit else ['мл', 'г', 'л'])]


# Сюди пишемо кожен випадок, коли зі складеного значення взято першу
# складову. Це технічний дефолт, а не остаточне рішення: у довіднику Rozetka
# складених розмірів («S/M», «L/XL») немає взагалі, тож характеристика
# інакше не пройшла б. Питання про правильну конвенцію поставлене відділу
# адаптації; до відповіді значення позначені джерелом, щоб їх можна було
# знайти й переграти одним запитом.
COMPOSITE_SOURCE = 'composite_first_component'
_composite_trace = []

# Відповідь відділу адаптації (Барановська Ольга, 11.08.2026 08:58):
#   «Для товарів зі спареним розміром вказуйте в параметрі "Розмір" два
#    значення (наприклад, S та M), а також зазначайте їх у назві товару.»
# Тобто «S/M» — це НЕ одне значення й не перша складова, а два окремих теги
# <param name="Розмір"> у межах того самого оффера. Назва вже містить обидва
# («Боді Passion ADARA L/XL Чорний»), її не чіпаємо.
MULTI_VALUE_PARAMS = {'Розмір'}
# Довідник Rozetka сам каже, які параметри багатозначні: тип `List` проти
# `ComboBox`. Беремо це з нього, а не з памʼяті — у Лубрикантах, наприклад,
# List мають Ефекти, Форма випуску, Призначення й Тип упаковки, і кожне
# значення має йти окремим тегом, як уже робиться для Розміру.
def load_multi_params(cur):
    try:
        cur.execute("""SELECT DISTINCT param_name FROM rozetka_category_params
                       WHERE param_type = 'List'""")
        MULTI_VALUE_PARAMS.update(r['param_name'] for r in cur.fetchall())
    except psycopg2.Error:
        cur.connection.rollback()
_multi_values = {}          # (sku, param) → [значення, значення]

# Один і той самий розмір різні категорії Rozetka називають по-різному:
# у частині довідників «XXL», у частині «2XL». Постачальник дає обидві форми,
# тому складову шукаємо і в тому, і в іншому написанні.
SIZE_FORMS = {
    'XXL': ['XXL', '2XL'], '2XL': ['2XL', 'XXL'],
    'XXXL': ['XXXL', '3XL'], '3XL': ['3XL', 'XXXL'],
    'XXXXL': ['XXXXL', '4XL'], '4XL': ['4XL', 'XXXXL'],
    '5XL': ['5XL', 'XXXXXL'], '6XL': ['6XL'], '7XL': ['7XL'],
}


def _match_value(value: str, allowed: list, vmap: dict, _param: str = '',
                 _sku: str = ''):
    """Підібрати значення зі списку довідника.

    Постачальник часто дає складені значення: «S/M», «Тканина, Латекс»,
    «80 % поліамід, 20 % еластан». Rozetka таких не знає — беремо першу
    складову, яка є в довіднику, інакше відкидаємо характеристику.
    """
    low = {a.lower(): a for a in allowed}
    v = value.strip()

    def _lookup(part: str):
        """Складова довідника з урахуванням альтернативних написань розміру."""
        for form in SIZE_FORMS.get(part.upper(), [part]):
            hit = vmap.get(form.lower()) or low.get(form.lower())
            if hit:
                return hit
        return None

    # Для «Розмір» розбиття має пріоритет над збігом цілого значення: у частині
    # категорій довідник містить і сам складений варіант («XXL/XXXL»), і тоді
    # без цієї перевірки ми повертали б одне значення замість двох, як просить
    # відділ адаптації.
    if _param in MULTI_VALUE_PARAMS and re.search(r'[\/]', v):
        parts = [p.strip() for p in v.split('/') if p.strip()]
        found = [h for h in (_lookup(p) for p in parts) if h]
        found = list(dict.fromkeys(found))
        if len(found) > 1:
            _composite_trace.append((_sku, _param, v, found[0]))
            _multi_values[(_sku, _param)] = found
            return found[0]

    if v.lower() in vmap:
        return vmap[v.lower()]
    if v.lower() in low:
        return low[v.lower()]
    for cand in _unit_candidates(v):
        if cand.lower() in low:
            return low[cand.lower()]
    # Збираємо ВСІ складові, що є в довіднику, а не лише першу: для «Розмір»
    # Rozetka чекає окремий тег на кожну (див. MULTI_VALUE_PARAMS). Повертаємо
    # усе одно першу — решта логіки (назва, опис) працює зі скалярним значенням.
    hits, composite = [], False
    # Вертикальна риска — роздільник наших витягнутих значень («Гель | Крем»).
    # Без неї складене значення не збігалося з довідником узагалі, і частина
    # заповнених характеристик мовчки не доходила до фіду.
    for part in re.split(r'[\/,;|]|\s+та\s+|\s+і\s+', v):
        part = re.sub(r'^\d+\s*%?\s*', '', part).strip(' .%')
        if not part:
            continue
        hit = _lookup(part)
        if hit and hit not in hits:
            hits.append(hit)
            if part.strip().lower() != v.lower():
                composite = True
    if hits:
        if composite:
            _composite_trace.append((_sku, _param, v, hits[0]))
        if len(hits) > 1 and _param in MULTI_VALUE_PARAMS:
            _multi_values[(_sku, _param)] = hits
        return hits[0]
    return None


def fit_params(raw: dict, rz_id: str, official: dict, _sku: str = '') -> dict:
    """Лишити тільки те, що Rozetka справді покаже.

    Суворість тут асиметрична, і це не недогляд — так написано в довідці
    продавця (p210), де дві сусідні фрази означають різне:

      «Якщо ви вказали ЗНАЧЕННЯ характеристики, якого ще немає в категорії
       ROZETKA (наприклад: новий колір або розмір) — ми додамо його
       автоматично.»
      «Якщо ХАРАКТЕРИСТИКА в категорії відсутня, вона не буде показана.»

    Тому назва звіряється з довідником суворо: невідому Rozetka просто не
    покаже, і характеристика зникне з картки. Значення ж звіряється мʼяко —
    спершу пробуємо підібрати відоме (щоб товар групувався з чужими
    картками), а якщо не вийшло, віддаємо своє: маркетплейс додасть його
    в довідник сам. Сувора перевірка значень коштувала 212 товарів.
    """
    spec = official.get(rz_id, {})
    if not spec:
        return raw
    alias = PARAM_ALIAS.get(rz_id, {})
    out, effects = {}, []
    for name, value in raw.items():
        v = str(value).strip()
        if not v:
            continue
        if name in EFFECTS and v.lower() in ('так', 'yes', 'true'):
            effects.append(EFFECTS[name])
            continue
        target = alias.get(name, name)
        hit = spec.get(target.lower())
        if not hit:
            continue
        off_name, allowed = hit
        if len(allowed) > 1:
            matched = _match_value(v, allowed,
                                   VALUE_ALIAS.get((rz_id, off_name), {}),
                                   off_name, _sku)
            if matched is None:
                if len(allowed) < OPEN_VOCABULARY:
                    continue        # закритий перелік — своє значення тут хибне
                pass                # відкритий словник — Rozetka додасть нове
            else:
                v = matched
        out[off_name] = v
    if effects and 'ефекти' in spec:
        out[spec['ефекти'][0]] = ', '.join(sorted(set(effects)))
    return out


