def word_gender(noun: str) -> str:
    """Рід іменника за закінченням: досить точно для узгодження прикметника."""
    w = (noun or '').split()[-1].lower()
    if w in GENDER_EXCEPT:
        return GENDER_EXCEPT[w]
    if w.endswith(('и', 'і', 'а́', 'ї')) and not w.endswith(('ка', 'ля')):
        return 'p'
    if w.endswith(('а', 'я')):
        return 'f'
    if w.endswith(('о', 'е')):
        return 'n'
    return 'm'


