# Рід для узгодження прикметника матеріалу. Здебільшого визначається
# закінченням; винятки — невідмінювані запозичення.
GENDER_EXCEPT = {'боді': 'n', 'бікіні': 'n', 'кімоно': 'n', 'манто': 'n'}


def word_gender(noun: str) -> str:
    """Рід іменника за закінченням: досить точно для узгодження прикметника."""
    w = (noun or '').split()[-1].lower()
    if w in GENDER_EXCEPT:
        return GENDER_EXCEPT[w]
    if w.endswith(('и', 'і', 'а́', 'ї')) and not w.endswith(('ка', 'ля')):
        return 'p'
    if w.endswith(('а', 'я')):
        return 'f'
    if w.endswith(('о', 'е')):
        return 'n'
    return 'm'


def specific_type(prm: dict) -> str:
    """Найточніший тип товару з наших характеристик, або порожньо."""
    for k in TYPE_PARAMS:
        v = (prm.get(k) or '').split('|')[0].split(',')[0].strip().lower()
        if v and v not in NOT_A_NOUN and 1 <= len(v.split()) <= 2:
            return v
    return ''


AUDIENCE = {'Жіноча': 'для жінок', 'Чоловіча': 'для чоловіків',
            'Унісекс': 'для пар', 'Для пар': 'для пар'}

# У постачальника <vendor> подекуди заповнений заглушкою. Як ключ це сміття
# («кляп без бренда»), тому такі значення в фрази не підставляємо.
NOT_A_BRAND = {'без бренда', 'без бренду', 'no brand', 'noname', 'no name',
               'немає', 'n/a', '-'}


def real_vendor(vendor: str) -> str:
    return '' if (vendor or '').strip().lower() in NOT_A_BRAND else (vendor or '').strip()


# Обрив фрази на прийменнику дає сміття на кшталт «вібратор з», тому
# хвостові службові слова відкидаємо, а не добираємо наступне слово:
# «вібратор з обертанням» вже трислівний ключ, а «вібратор з» — не ключ.
TAIL_STOP = {'з', 'із', 'зі', 'для', 'на', 'в', 'у', 'до', 'та', 'і', 'й',
             'під', 'без', 'по', 'при', 'над', 'від'}


def name_phrase(name: str, vendor: str) -> str:
    """Перші слова назви — вже граматично узгоджена фраза, беремо як є."""
    t = name
    if vendor and vendor in t:
        t = t.split(vendor)[0]
    t = re.split(r'[,(]', t)[0]
    words = [w for w in t.split() if w and not w.isdigit()
             and not re.fullmatch(r'[A-Za-z0-9\-.]+', w)]
    # Беремо до 4 слів — стільки ж, скільки дозволяє ліміт фрази. Обрізання
    # на двох словах давало «лубрикант на водній» замість «…водній основі»
    # і «мило у формі» замість «мило у формі пеніса»: 1235 таких випадків.
    words = words[:MAX_WORDS]
    while words and words[-1].lower() in TAIL_STOP:
        words.pop()
    return ' '.join(words).strip()


def build(name: str, vendor: str, category: str, prm: dict) -> list:
    vendor = real_vendor(vendor)
    cat = CATEGORY.get((category or '').strip())
    single, gender, purpose = cat if cat else ('', 'm', '')
    head = name_phrase(name, vendor)
    material = (prm.get('Матеріал') or '').split('|')[0].strip()
    audience = AUDIENCE.get((prm.get('Стать') or '').strip())

    out, seen = [], set()

    def add(phrase: str):
        p = re.sub(r'\s+', ' ', (phrase or '')).strip().lower()
        if not (MIN_WORDS <= len(p.split()) <= MAX_WORDS):
            return
        if p in seen or any(s in p.split() for s in STOP):
            return
        seen.add(p)
        out.append(p)

    # 1. фраза з назви + бренд — найточніший ключ
    if head and vendor:
        add(f'{head} {vendor}')
    # 2. тип із категорії + бренд
    if single and vendor:
        add(f'{single} {vendor}')
    # 3. матеріал, узгоджений за родом типу
    if material in MATERIAL and single:
        add(f'{MATERIAL[material][GENDER_IDX[gender]]} {single}')
    # 4. призначення категорії
    if single and purpose:
        add(f'{single} {purpose}')
    # 5. аудиторія з характеристики
    if single and audience:
        add(f'{single} {audience}')
    # ── конкретний тип із характеристик: для слабких товарів це головне
    # джерело фраз. Прикметник матеріалу узгоджуємо з РОДОМ цього типу,
    # а не категорійного: «шкіряні наручники», не «шкіряний наручники».
    col = (prm.get('Колір') or '').split('|')[0].strip()
    spec = specific_type(prm)
    if spec:
        sg = word_gender(spec)
        if vendor:
            add(f'{spec} {vendor}')
        if material in MATERIAL:
            add(f'{MATERIAL[material][GENDER_IDX[sg]]} {spec}')
        if purpose:
            add(f'{spec} {purpose}')
        if col.lower() in COLOR:
            add(f'{spec} {COLOR[col.lower()][GENDER_IDX[sg]]}')
        if audience:
            add(f'{spec} {audience}')


    # 6. колір і розмір як самостійні уточнення до категорійного типу
    if single:
        if col.lower() in COLOR:
            add(f'{single} {COLOR[col.lower()][GENDER_IDX[gender]]}')
        size = (prm.get('Розмір') or '').split('|')[0].strip()
        if size and len(size) <= 12:
            add(f'{single} розмір {size}'.lower())

    # 7. запасний варіант: сама фраза з назви
    if head and len(head.split()) >= 2:
        add(head)

    res, total = [], 0
    for p in out[:MAX_PHRASES]:
        if total + len(p) + 2 > MAX_FIELD:
            break
        res.append(p)
        total += len(p) + 2
    return res


def validate(phrases: list) -> list:
    """Перевірка фраз будь-якого походження — Рівня 1, LLM чи руки.

    Потрібна саме тому, що людина й LLM на цьому спотикаються: бренд
    «Art of Sex» — це три слова, і «жіноча портупея Art of Sex» вилітає
    за ліміт у 4 слова, хоча на око виглядає короткою фразою.
    """
    problems = []
    for p in phrases:
        w = (p or '').split()
        if len(w) < MIN_WORDS:
            problems.append((p, f'замало слів ({len(w)})'))
        elif len(w) > MAX_WORDS:
            problems.append((p, f'забагато слів ({len(w)}), ліміт {MAX_WORDS}'))
        elif any(s in [x.lower() for x in w] for s in STOP):
            problems.append((p, 'стоп-слово, Prom додає його сам'))
    if sum(len(p) + 2 for p in phrases) > MAX_FIELD:
        problems.append((', '.join(phrases)[:40] + '…', 'поле задовге'))
    return problems


def load(feed=FEED):
    root = ET.parse(feed).getroot()
    cats = {c.get('id'): (c.text or '') for c in root.findall('.//category')}
    for o in root.findall('.//offer'):
        prm = {p.get('name'): (p.text or '').strip() for p in o.findall('param')}
        yield {
            'sku': o.findtext('vendorCode'),
            # ВАЖЛИВО: <name> у фіді Prom — РОСІЙСЬКЕ поле, українське в
            # <name_ua>. Ключі українські, тому джерелом має бути name_ua,
            # інакше у фразах зʼявляється російський текст.
            'name': o.findtext('name_ua') or o.findtext('name') or '',
            'vendor': (o.findtext('vendor') or '').strip(),
            'category': cats.get(o.findtext('categoryId'), ''),
            'prm': prm,
        }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--limit', type=int)
    ap.add_argument('--report', action='store_true')
    ap.add_argument('--pilot')
    ap.add_argument('--out')
    a = ap.parse_args()

    items = list(load())
    if a.pilot:
        keep = {x['sku'] for x in json.load(open(a.pilot))}
        items = [x for x in items if x['sku'] in keep]
    if a.limit:
        items = items[:a.limit]

    dist, rows = collections.Counter(), []
    for it in items:
        kw = build(it['name'], it['vendor'], it['category'], it['prm'])
        dist[min(len(kw), MAX_PHRASES)] += 1
        rows.append({'sku': it['sku'], 'name': it['name'],
                     'category': it['category'], 'nparam': len(it['prm']),
                     'level1': kw})

    total = len(rows)
    print(f'товарів: {total}')
    for k in sorted(dist):
        print(f'   {k} фраз — {dist[k]:5} ({dist[k] * 100 // total}%)')
    enough = sum(v for k, v in dist.items() if k >= 3)
    print(f'\n≥3 фрази — Рівень 1 достатній : {enough} ({enough * 100 // total}%)')
    print(f'<3 фраз  — потрібен Рівень 2+  : {total - enough} '
          f'({(total - enough) * 100 // total}%)')

    if a.out:
        json.dump(rows, open(a.out, 'w'), ensure_ascii=False, indent=1)
        print(f'\n→ {a.out}')
    if not a.report:
        print('\nПРИКЛАДИ:')
        for x in rows[:8]:
            print(f"\n  {x['sku']}  {x['name'][:62]}")
            for p in x['level1']:
                print(f'      • {p}')


if __name__ == '__main__':
    main()
