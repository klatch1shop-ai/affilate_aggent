def name_phrase(name: str, vendor: str) -> str:
    """Перші слова назви — вже граматично узгоджена фраза, беремо як є."""
    t = name
    if vendor and vendor in t:
        t = t.split(vendor)[0]
    t = re.split(r'[,(]', t)[0]
    words = [w for w in t.split() if w and not w.isdigit()
             and not re.fullmatch(r'[A-Za-z0-9\-.]+', w)]
    # Беремо до 4 слів — стільки ж, скільки дозволяє ліміт фрази. Обрізання
    # на двох словах давало «лубрикант на водній» замість «…водній основі»
    # і «мило у формі» замість «мило у формі пеніса»: 1235 таких випадків.
    words = words[:MAX_WORDS]
    while words and words[-1].lower() in TAIL_STOP:
        words.pop()
    return ' '.join(words).strip()



