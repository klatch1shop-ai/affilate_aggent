    out, seen = [], set()

    def add(phrase: str):
        p = re.sub(r'\s+', ' ', (phrase or '')).strip().lower()
        if not (MIN_WORDS <= len(p.split()) <= MAX_WORDS):
            return
        if p in seen or any(s in p.split() for s in STOP):
            return
        seen.add(p)
        out.append(p)

