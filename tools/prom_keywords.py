def brand_cyr(vendor: str, lang: str = 'ua') -> str:
    """Кириличне написання бренду або порожньо, якщо його не існує."""
    v = re.sub(r'\s*\(.*?\)', '', vendor or '').strip()
    pair = BRAND_CYR.get(v)
    if not pair:
        for k, val in BRAND_CYR.items():
            if k.lower() == v.lower():
                pair = val
                break
    return (pair[0] if lang == 'ua' else pair[1]) if pair else ''


