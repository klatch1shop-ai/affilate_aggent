#!/bin/bash
# Автономне продовження роботи після відновлення ліміту.
#
# Задум простий: cron пробує регулярно, і коли годинний ліміт вичерпано,
# спроба просто падає — наступна пройде. Ніякого опитування квоти не
# потрібно, бо API її не показує; повтор за розкладом і є механізмом
# відновлення.
#
# Захист від накладання: flock. Дві копії одночасно писали б у ті самі
# файли й чергу.
#
# Ставиться в crontab ЦІЄЇ машини, не сервера: claude CLI є тільки тут.

set -uo pipefail
DIR=/home/tekken/agent-system
LOG=$DIR/logs/resume_worker.log
LOCK=/tmp/resume_worker.lock
QUEUE=$DIR/docs/work_queue.md

mkdir -p "$DIR/logs"
exec 9>"$LOCK"
if ! flock -n 9; then
    echo "$(date '+%F %T') пропуск: попередній запуск ще працює" >> "$LOG"
    exit 0
fi

# Осиротілий [~] повертаємо в роботу.
#
# Підстава: flock вище гарантує, що іншого прогону НЕМАЄ. Отже пункт, який
# лишився в стані [~], — це слід прогону, що обірвався (вичерпаний ліміт,
# перезавантаження, вбитий процес). Робітник шукає лише [ ], тому такий
# пункт зависав би назавжди, а черга виглядала б порожньою: 24.08 через це
# простояли пʼять годин при живому cron.
if grep -q '^- \[~\]' "$QUEUE"; then
    n=$(grep -c '^- \[~\]' "$QUEUE")
    sed -i 's/^- \[~\]/- [ ]/' "$QUEUE"
    echo "$(date '+%F %T') повернуто в чергу осиротілих пунктів: $n" >> "$LOG"
fi

# Немає жодного пункту [ ] — працювати нема над чим.
if ! grep -q '^- \[ \]' "$QUEUE"; then
    echo "$(date '+%F %T') черга порожня" >> "$LOG"
    exit 0
fi

PROMPT="Прочитай docs/work_queue.md і docs/work_journal.md у $DIR.
Візьми ПЕРШИЙ пункт зі станом [ ], познач його [~] і виконай.
Дотримуйся правил у кінці work_queue.md — особливо заборони публікувати
фіди й чіпати Rozetka NOIRE.
Після завершення: постав [x] (або [!], якщо потрібне рішення власника),
допиши підсумок і замір у docs/work_journal.md.
Працюй мовчки, без запитань — відповіді не буде, сесія неінтерактивна."

echo "$(date '+%F %T') старт" >> "$LOG"
cd "$DIR" || exit 1
# Повний шлях, а не ім'я: cron має мінімальний PATH без ~/.local/bin, і
# запуск 29 разів поспіль падав з кодом 127 «No such file or directory».
# Помилка була мовчазна для мене — журнал писався, роботи не було.
CLAUDE=/home/tekken/.local/bin/claude
# Режим: acceptEdits дозволяє лише правки файлів, а bash-команди в
# неінтерактивному -p мовчки ВІДХИЛЯЮТЬСЯ — спитати нікого. Саме тому
# автономні прогони «нічого не робили». Для роботи без нагляду потрібен
# bypassPermissions. Межі тримають не дозволи, а docs/work_queue.md,
# SKILL-22 і запобіжник shared/utils/consent.py на публікації.
timeout 3600 "$CLAUDE" -p "$PROMPT" \
    --permission-mode bypassPermissions \
    --fallback-model claude-sonnet-5 \
    >> "$LOG" 2>&1
rc=$?
if [ $rc -eq 0 ]; then
    echo "$(date '+%F %T') завершено успішно" >> "$LOG"
else
    # Найімовірніша причина — вичерпаний ліміт. Наступний запуск за
    # розкладом спробує знову; це і є «продовження по відновленню».
    echo "$(date '+%F %T') невдача (код $rc) — повтор наступним запуском" >> "$LOG"
fi
exit 0
