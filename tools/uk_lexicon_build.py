#!/usr/bin/env python3
"""Збирає два словники, на які спирається ознака російської мови.

Навіщо окремий крок збірки. Попередні дві версії ознаки були РУЧНИМ переліком
основ, і обидві провалились однаково: перелік, зібраний з голови, і хибно
тривожив («ширина», «рукоятка» — спільні для обох мов), і недобирав («Питание»,
«Состояние» — жодної основи з переліку). 22.08 перелік переписали — і 25.08
незалежна перевірка знайшла 10 російських назв характеристик на 1189 вживань,
яких він знову не бачив («Рабочий профиль», «Расход воздуха», «Пневматический»).

Причина не в конкретному переліку, а в самому підході: російських слів без
жодної орфографічної позначки («набор», «нет», «ключи», «металл», «класс»,
«воздух», «сеть», «нож») регексом не впіймати в принципі — вони пишуться
однаково допустимими для української літерами. Потрібен словник, а не регекс.

Виходи:
  data/uk_wordforms.txt.gz  — 1.55 млн українських словоформ (пакет wukrainian,
                              /usr/share/dict/ukrainian). Джерело істини для
                              «це слово українське».
  data/toptul_ru_lexicon.txt — російські словоформи, які трапляються в каталозі
                              TOPTUL. Дві частини, обидві НЕ вигадані:
                              1) вивід із `toptul_translation.src` — рядків,
                                 які перекладач уже визнав російськими;
                              2) ручна частина `RU_MANUAL` нижче — слова з
                                 поточного фіду, яких у таблиці ще немає.

Запуск: python3 tools/uk_lexicon_build.py  (потрібен /usr/share/dict/ukrainian,
є на ноутбуці; на сервер їде готовий .gz).
"""
