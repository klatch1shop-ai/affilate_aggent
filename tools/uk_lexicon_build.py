def build_uk() -> int:
    if not os.path.exists(SRC_DICT):
        print(f'НЕМАЄ {SRC_DICT}. Пакет: sudo apt install wukrainian', file=sys.stderr)
        return 0
    ws = set()
    with open(SRC_DICT, encoding='utf-8') as f:
        for line in f:
            w = line.strip().lower()
            if w and WORD.match(w):
                ws.add(w.replace('’', 'ʼ').replace("'", 'ʼ'))
    data = '\n'.join(sorted(ws)).encode()
    os.makedirs(os.path.dirname(OUT_UK), exist_ok=True)
    with open(OUT_UK, 'wb') as f:
        f.write(gzip.compress(data, 9))
    print(f'{OUT_UK}: {len(ws)} словоформ, {os.path.getsize(OUT_UK)} Б')
    return len(ws)


def build_ru(uk: set) -> int:
    """Російський лексикон: вивід із таблиці перекладів + ручна частина.

    Вивід із таблиці: слово є в `src` (рядок, який перекладач визнав
    російським), його НЕМАЄ в `dst` (бо dst — уже українське) і немає в
    українському словнику. Третя умова прибирає спільні для обох мов слова:
    саме на них двічі зривались попередні ознаки.
    """
    tok = re.compile(r"[а-яіїєґёыэъ]+(?:[ʼ'’][а-яіїєґ]+)*", re.I)

    def words(s):
        return {w.lower().replace("'", 'ʼ').replace('’', 'ʼ')
                for w in tok.findall(s or '') if len(w) > 2}

    auto = set()
    try:
        from shared.utils.db import get_connection
        conn = get_connection()
        cur = conn.cursor()
        cur.execute('select src, dst from toptul_translation')
        rows = cur.fetchall()
        src_w, dst_w = set(), set()
        for r in rows:
            src_w |= words(r['src'])
            dst_w |= words(r['dst'])
        auto = src_w - dst_w - uk
        print(f'із toptul_translation ({len(rows)} пар): {len(auto)} слів')
    except Exception as e:                                   # noqa: BLE001
        print(f'БД недоступна ({e}) — лише ручна частина', file=sys.stderr)

    manual = {w for w in RU_MANUAL.split() if len(w) > 2}
    # Ручна частина не мусить сваритись з українським словником: слово, яке в
    # ньому є, спільне для обох мов, і в лексиконі російського йому не місце.
    clash = sorted(manual & uk)
    if clash:
        print(f'ВИКИНУТО з ручної частини (є в укр. словнику): {clash}')
    manual -= uk

    lex = sorted(auto | manual)
    with open(OUT_RU, 'w', encoding='utf-8') as f:
        f.write('# Російські словоформи каталогу TOPTUL. Збирається\n'
                '# tools/uk_lexicon_build.py: вивід із toptul_translation.src\n'
                '# плюс ручна частина RU_MANUAL. Руками цей файл не правлять.\n')
        f.write('\n'.join(lex) + '\n')
    print(f'{OUT_RU}: {len(lex)} слів (авто {len(auto)}, ручних {len(manual)})')
    return len(lex)


if __name__ == '__main__':
    # На сервері /usr/share/dict/ukrainian немає — туди їде готовий .gz, і
    # перезбирати його там не треба. А от російський лексикон збирається саме
    # на сервері: `toptul_translation` живе в тамтешньому PostgreSQL.
    if not os.path.exists(OUT_UK):
        if not build_uk():
            sys.exit(1)
    elif '--rebuild-uk' in sys.argv:
        build_uk()
    else:
        print(f'{OUT_UK} уже є — пропускаю (--rebuild-uk щоб перезібрати)')
    with gzip.open(OUT_UK, 'rt', encoding='utf-8') as f:
        uk = {w.strip() for w in f}
    build_ru(uk)
