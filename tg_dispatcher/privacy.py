"""Спільне приховування контактів у тексті."""

import re


_SEP = r'[ ()-]*'
_PHONE = re.compile(
    rf'(?<![\d+])\+?\(?'
    rf'(?:3{_SEP}8{_SEP}0(?:{_SEP}\d){{9}}|0(?:{_SEP}\d){{9}})'
    rf'\)?(?!\d)'
)
_EMAIL = re.compile(r"[\w.!#$%&'*+/=?^`{|}~-]+@[\w-]+(?:\.[\w-]+)+")


def mask_private(text: str) -> str:
    """Замінити телефони та електронні адреси без зміни інших чисел."""
    return _PHONE.sub('[телефон приховано]', _EMAIL.sub('[email приховано]', text))
